#!/usr/bin/env python3
"""Tests for `lockdates.py`'s gate modes (§1.2's freshness gate), with no network.

Run with either:
  python3 -I tasks/deps-upgrade/tools/gbase/tests/test_lockdates.py
  python3 -m pytest tasks/deps-upgrade/tools/gbase/tests/test_lockdates.py

Every run passes `--date-source`, which reads registry facts from a file and never the
network: `fixtures/registry-recorded.json` holds crates.io's `created_at` for a few
crates as the 2026-10-28 gates recorded them (rustyline, radix_trie, tokio-tungstenite,
tungstenite), and the toy crates `alpha` and `beta` are written by the tests. Each test
asserts the exit status the gate documents — 0 eligible or waived, 1 too young (and only
then), 2 no verdict — and the lines a caller reads.

Not here: the driver's handling of gate output that ends before its verdict (A-11's
partial-output test), which is gbase.sh's, not this script's.
"""

from __future__ import annotations

import json
import pathlib
import subprocess
import sys
import tempfile

HERE = pathlib.Path(__file__).resolve().parent
LOCKDATES = HERE.parent / "lockdates.py"
RECORDED = HERE / "fixtures" / "registry-recorded.json"
CRATES_IO = "registry+https://github.com/rust-lang/crates.io-index"
MAX = "2026-10-14T19:53:00Z"

TOY = {
    "crates": {
        "alpha": [
            {"num": "1.0.0", "created_at": "2026-01-01T00:00:00Z", "yanked": False},
            {"num": "1.0.1", "created_at": "2026-10-01T00:00:00Z", "yanked": False},
            {"num": "1.0.2", "created_at": "2026-10-20T00:00:00Z", "yanked": False},
        ],
        "beta": [
            {"num": "1.0.0", "created_at": "2026-01-01T00:00:00Z", "yanked": False},
            {"num": "1.0.1", "created_at": "2026-10-02T00:00:00Z", "yanked": True},
            {"num": "1.0.2", "created_at": "2026-10-21T00:00:00Z", "yanked": False},
        ],
    },
    "npm": {
        "left-pad": {"time": {"1.3.0": "2018-04-09T00:00:00Z", "1.4.0": "2026-10-20T00:00:00Z"}, "optional": {}},
    },
}


def lock(*packages: tuple) -> str:
    """A Cargo.lock: (name, version) from crates.io, (name, version, deps) with dependencies,
    (name, version, deps, None) for a workspace member (no source)."""
    out = ["# This file is automatically @generated by Cargo.", "version = 4", ""]
    for p in packages:
        name, version = p[0], p[1]
        deps = p[2] if len(p) > 2 else []
        out += ["[[package]]", 'name = "%s"' % name, 'version = "%s"' % version]
        if not (len(p) > 3 and p[3] is None):
            out.append('source = "%s"' % CRATES_IO)
        if deps:
            out.append("dependencies = [")
            out += [' "%s",' % d for d in deps]
            out.append("]")
        out.append("")
    return "\n".join(out)


def run(d: pathlib.Path, *args: str, source: pathlib.Path | None = None) -> tuple[int, str]:
    if source is None:
        source = d / "toy.json"
        source.write_text(json.dumps(TOY), encoding="utf-8")
    cmd = [sys.executable, "-I", str(LOCKDATES), *args, "--date-source", str(source)]
    proc = subprocess.run(cmd, capture_output=True, text=True, cwd=str(d))
    return proc.returncode, proc.stdout + proc.stderr


def gate(parent: str, new: str, *extra: str, max_date: str = MAX, source: pathlib.Path | None = None) -> tuple[int, str]:
    with tempfile.TemporaryDirectory() as t:
        d = pathlib.Path(t)
        (d / "parent.lock").write_text(parent, encoding="utf-8")
        (d / "new.lock").write_text(new, encoding="utf-8")
        for i, e in enumerate(extra):  # a waivers file's text, written beside the locks
            (d / ("waivers%d.txt" % i)).write_text(e, encoding="utf-8")
        flags = []
        for i, _ in enumerate(extra):
            flags += ["--waivers", str(d / ("waivers%d.txt" % i))]
        return run(d, "--gate", "--max-date", max_date, *flags, str(d / "parent.lock"), str(d / "new.lock"), source=source)


PARENT = lock(("alpha", "1.0.0"), ("beta", "1.0.0", ["alpha"]), ("member", "0.1.0", ["alpha", "beta"], None))


def test_an_eligible_move_passes() -> None:
    rc, out = gate(PARENT, lock(("alpha", "1.0.1"), ("beta", "1.0.0", ["alpha"]), ("member", "0.1.0", ["alpha", "beta"], None)))
    assert rc == 0, out
    assert "  eligible   alpha 1.0.1  2026-10-01T00:00:00Z" in out, out
    assert "too young: 0" in out, out


def test_a_too_young_move_fails_with_its_step_backs_dependents_first() -> None:
    rc, out = gate(PARENT, lock(("alpha", "1.0.2"), ("beta", "1.0.2", ["alpha"]), ("member", "0.1.0", ["alpha", "beta"], None)))
    assert rc == 1, out
    # beta depends on alpha, so beta's step-back comes first; beta 1.0.1 is yanked, so
    # beta steps back to the parent's own 1.0.0
    assert out.index("cargo update -p beta@1.0.2 --precise 1.0.0") < out.index("cargo update -p alpha@1.0.2 --precise 1.0.1"), out
    assert "step-back: beta@1.0.2 1.0.0\nstep-back: alpha@1.0.2 1.0.1" in out, out
    assert "(not from a registry, not dated: 0)" in out, out


def test_a_recorded_waiver_admits_exactly_its_version() -> None:
    new = lock(("alpha", "1.0.2"), ("beta", "1.0.2", ["alpha"]), ("member", "0.1.0", ["alpha", "beta"], None))
    rc, out = gate(PARENT, new, "alpha@1.0.2  the fix of an advisory (test)\nbeta@1.0.2  the pair waits on it (test)\n")
    assert rc == 0, out
    assert out.count("  waived     ") == 2, out
    rc, out = gate(PARENT, new, "alpha@1.0.2  only alpha (test)\n")
    assert rc == 1 and "step-back: beta@1.0.2 1.0.0" in out and "alpha@1.0.2 1.0.1" not in out, out


def test_a_waiver_without_its_reason_is_no_verdict() -> None:
    rc, out = gate(PARENT, PARENT, "alpha@1.0.2\n")
    assert rc == 2 and "with its reason" in out, out


def test_a_failed_lookup_is_no_verdict() -> None:
    rc, out = gate(PARENT, lock(("alpha", "1.0.0"), ("gamma", "0.1.0"), ("beta", "1.0.0", ["alpha"])))
    assert rc == 2, out
    assert "no verdict" in out and "gamma" in out, out


def test_a_crate_from_another_source_is_no_verdict() -> None:
    new = PARENT.replace('name = "alpha"\nversion = "1.0.0"\nsource = "%s"' % CRATES_IO,
                         'name = "alpha"\nversion = "1.0.1"\nsource = "git+https://example.invalid/alpha#0"')
    rc, out = gate(PARENT, new)
    assert rc == 2 and "cannot date" in out, out


def test_two_modes_are_no_verdict_before_anything_is_read() -> None:
    with tempfile.TemporaryDirectory() as t:
        rc, out = run(pathlib.Path(t), "--gate", "--pins", "crates", "--max-date", MAX, "alpha@1.0.0")
        assert rc == 2 and "give one of" in out, out


def test_recorded_rustyline_19_is_too_young_at_the_cut_with_no_step_back() -> None:
    # rustyline 19.0.0 was published 2026-10-17T09:32:27Z, after the max date; no older 19.x exists
    rc, out = gate(lock(("rustyline", "18.0.1", ["radix_trie"]), ("radix_trie", "0.3.0")),
                   lock(("rustyline", "19.0.0", ["radix_trie"]), ("radix_trie", "0.3.0")), source=RECORDED)
    assert rc == 1, out
    assert "no-step-back: rustyline@19.0.0" in out, out


def test_recorded_rustyline_18_0_1_steps_back_to_18_0_0_before_its_release() -> None:
    rc, out = gate(lock(("rustyline", "17.0.2", ["radix_trie 0.2.1"]), ("radix_trie", "0.2.1")),
                   lock(("rustyline", "18.0.1", ["radix_trie 0.3.0"]), ("radix_trie", "0.2.1"), ("radix_trie", "0.3.0")),
                   max_date="2026-05-01T00:00:00Z", source=RECORDED)
    assert rc == 1, out
    assert "  eligible   radix_trie 0.3.0" in out and "step-back: rustyline@18.0.1 18.0.0" in out, out


def test_recorded_tokio_tungstenite_0_30_is_eligible_at_the_cut() -> None:
    rc, out = gate(lock(("tokio-tungstenite", "0.28.0", ["tungstenite"]), ("tungstenite", "0.28.0")),
                   lock(("tokio-tungstenite", "0.30.0", ["tungstenite"]), ("tungstenite", "0.30.0")), source=RECORDED)
    assert rc == 0, out
    assert "eligible: 2" in out, out


def test_a_bun_lock_entry_younger_than_the_max_date_fails() -> None:
    with tempfile.TemporaryDirectory() as t:
        d = pathlib.Path(t)
        body = '{\n  "lockfileVersion": 1,\n  "packages": {\n    "left-pad": ["left-pad@%s", "", {}, "sha512-x"],\n  },\n}\n'
        (d / "old.lock").write_text(body % "1.3.0", encoding="utf-8")
        (d / "new.lock").write_text(body % "1.4.0", encoding="utf-8")
        rc, out = run(d, "--bun-lock", str(d / "old.lock"), "--max-date", MAX)
        assert rc == 0 and "  eligible   left-pad 1.3.0" in out, out
        rc, out = run(d, "--bun-lock", str(d / "new.lock"), "--max-date", MAX)
        assert rc == 1 and "  TOO YOUNG  left-pad 1.4.0" in out, out


def main() -> int:
    tests = [(name, fn) for name, fn in sorted(globals().items()) if name.startswith("test_") and callable(fn)]
    failures = 0
    for name, fn in tests:
        try:
            fn()
        except Exception as exc:  # noqa: BLE001 — report every failure, keep going
            failures += 1
            print(f"FAIL {name}: {exc}")
        else:
            print(f"ok   {name}")
    print(f"\n{len(tests) - failures}/{len(tests)} passed")
    return 1 if failures else 0


if __name__ == "__main__":
    sys.exit(main())
